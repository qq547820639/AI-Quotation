/** 生成相对当前的时间字符串 */
const now = dayjs();
const day = (offset: number, hour = 0, minute = 0): string =>
  now.add(offset, 'day').hour(hour).minute(minute).second(0).format('YYYY-MM-DD HH:mm:ss');
const dateOnly = (offset: number): string => now.add(offset, 'day').format('YYYY-MM-DD');

/** 日志 id 计数（全局唯一即可） */
let logSeq = 0;
const buildLog = (
  inquiryId: string,
  offsetDays: number,
  operator: string,
  operatorRole: string,
  type: LogType,
  content: string,
  result?: string,
): InquiryLog => {
  logSeq += 1;
  return {
    id: `log-${inquiryId}-${logSeq}`,
    inquiryId,
    time: day(offsetDays, 9, 30),
    operator,
    operatorRole,
    type,
    content,
    result,
  };
};

/** 构造询价明细（index 为该询价单内的明细序号，从 1 起） */
const buildItem = (
  inquiryId: string,
  index: number,
  material: Material,
  quantity: number,
  targetPrice?: number,
  remark?: string,
): InquiryItem => ({
  id: `item-${inquiryId}-${index}`,
  inquiryId,
  material,
  name: material.name,
  code: material.code,
  category: material.category,
  brand: material.brand,
  spec: material.spec,
  techParams: material.techParams,
  unit: material.unit,
  quantity,
  targetPrice,
  expectedDeliveryDate: dateOnly(20),
  remark,
  attachments: [],
});

